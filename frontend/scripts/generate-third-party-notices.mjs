import { createHash } from "node:crypto";
import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptsDirectory = path.dirname(fileURLToPath(import.meta.url));
const frontendDirectory = path.resolve(scriptsDirectory, "..");
const repositoryRoot = path.resolve(frontendDirectory, "..");
const lockPath = path.join(frontendDirectory, "package-lock.json");
const outputPath = path.join(repositoryRoot, "THIRD_PARTY_NOTICES.md");
const legalFilePattern = /^(licen[cs]e|copying|notice|third[-_ ]?party)/i;

const lock = JSON.parse(await readFile(lockPath, "utf8"));
const packages = [];
const textsByHash = new Map();

for (const [packagePath, lockEntry] of Object.entries(lock.packages || {})) {
  if (!packagePath.startsWith("node_modules/") || lockEntry.dev || lockEntry.devOptional) continue;

  const packageDirectory = path.join(frontendDirectory, packagePath);
  let manifest;
  try {
    manifest = JSON.parse(await readFile(path.join(packageDirectory, "package.json"), "utf8"));
  } catch (error) {
    throw new Error(`Cannot read installed manifest for ${packagePath}: ${error.message}`);
  }

  const legalFiles = (await readdir(packageDirectory, { withFileTypes: true }))
    .filter((entry) => entry.isFile() && legalFilePattern.test(entry.name))
    .map((entry) => entry.name)
    .sort((left, right) => left.localeCompare(right));
  const noticeIds = [];

  for (const fileName of legalFiles) {
    const content = normalizeText(await readFile(path.join(packageDirectory, fileName), "utf8"));
    noticeIds.push(registerNotice(content, `${manifest.name}@${manifest.version} (${fileName})`));
  }

  const license = formatValue(manifest.license ?? lockEntry.license ?? "Not declared");
  if (license === "Not declared" && noticeIds.length === 0) {
    throw new Error(`${manifest.name}@${manifest.version} has no declared license or installed legal notice`);
  }

  packages.push({
    name: manifest.name || packagePath.replace(/^node_modules\//, ""),
    version: manifest.version || lockEntry.version || "unknown",
    license,
    author: formatAuthor(manifest.author),
    repository: repositoryUrl(manifest.repository),
    noticeIds,
  });
}

const apacheLicense = [...textsByHash.values()].find((notice) =>
  notice.content.includes("Apache License") && notice.content.includes("Version 2.0, January 2004"),
);
for (const item of packages) {
  if (item.noticeIds.length) continue;
  const source = `${item.name}@${item.version} (generated from package metadata)`;
  if (item.license === "MIT") {
    item.noticeIds.push(registerNotice(mitLicense(item.author || item.name), source));
  } else if (item.license === "ISC") {
    item.noticeIds.push(registerNotice(iscLicense(item.author || item.name), source));
  } else if (item.license === "Apache-2.0" && apacheLicense) {
    apacheLicense.sources.push(source);
    item.noticeIds.push(apacheLicense);
  }
}

packages.sort((left, right) => `${left.name}@${left.version}`.localeCompare(`${right.name}@${right.version}`));
const texts = [...textsByHash.values()].sort((left, right) => left.sources[0].localeCompare(right.sources[0]));
texts.forEach((notice, index) => {
  notice.id = `L${String(index + 1).padStart(3, "0")}`;
});

const lines = [
  "# Third-party notices",
  "",
  "<!-- Generated by frontend/scripts/generate-third-party-notices.mjs; do not edit manually. -->",
  "",
  "The BIOMERO OME-Zarr Viewer production browser bundle includes the packages",
  "listed below. Each package remains subject to its upstream license. This file",
  "is generated from `frontend/package-lock.json` and the legal files installed",
  "with the non-development npm packages.",
  "",
  `Generated for frontend version \`${lock.version}\` with ${packages.length} production packages.`,
  "",
  "## Package inventory",
  "",
  "| Package | Declared license | Copyright/author | Upstream | Included legal text |",
  "| --- | --- | --- | --- | --- |",
];

for (const item of packages) {
  const notices = [...new Set(item.noticeIds.map((notice) => notice.id))];
  lines.push(
    `| \`${escapeTable(`${item.name}@${item.version}`)}\` | ${escapeTable(item.license)} | ${escapeTable(item.author || "—")} | ${item.repository ? `[source](${item.repository})` : "—"} | ${notices.length ? notices.map((id) => `[${id}](#${id.toLowerCase()})`).join(", ") : "Package metadata only"} |`,
  );
}

lines.push("", "## Included license and notice texts", "");
for (const notice of texts) {
  lines.push(
    `### ${notice.id}`,
    "",
    `Packages: ${notice.sources.map((source) => `\`${source}\``).join(", ")}`,
    "",
    "````text",
    notice.content,
    "````",
    "",
  );
}

await writeFile(outputPath, `${lines.join("\n").trimEnd()}\n`, "utf8");
console.log(`Wrote ${outputPath} (${packages.length} packages, ${texts.length} unique legal texts)`);

function normalizeText(value) {
  return value.replace(/\r\n/g, "\n").trim();
}

function registerNotice(content, source) {
  const normalized = normalizeText(content);
  const hash = createHash("sha256").update(normalized).digest("hex");
  let notice = textsByHash.get(hash);
  if (!notice) {
    notice = { id: "", content: normalized, sources: [] };
    textsByHash.set(hash, notice);
  }
  notice.sources.push(source);
  return notice;
}

function formatValue(value) {
  if (typeof value === "string") return value;
  if (value && typeof value === "object") return value.type || JSON.stringify(value);
  return String(value);
}

function formatAuthor(value) {
  if (typeof value === "string") return value;
  if (!value || typeof value !== "object") return "";
  return [value.name, value.email ? `<${value.email}>` : "", value.url ? `(${value.url})` : ""]
    .filter(Boolean)
    .join(" ");
}

function repositoryUrl(value) {
  const raw = typeof value === "string" ? value : value?.url;
  if (!raw) return "";
  return raw
    .replace(/^git\+/, "")
    .replace(/^git:\/\//, "https://")
    .replace(/\.git$/, "");
}

function escapeTable(value) {
  return String(value).replace(/\|/g, "\\|").replace(/\r?\n/g, " ");
}

